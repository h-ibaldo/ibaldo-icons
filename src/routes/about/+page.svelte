    <h1>About icon.design</h1>
    
    <h2>The Icon Library Built for Designers & Developers</h2>
    
    <p>icon.design is a growing library of free, open-source SVG icons designed for modern user interfaces. Whether you're building a web application, mobile app, or digital product, our carefully crafted icons provide the visual precision and flexibility you need—without licensing concerns or design compromises.</p>

    <h2>Why icon.design Exists</h2>
    
    <p>Most icon libraries treat each icon as a single, static design. We saw a gap: designers need options. They need flexibility. They need icons that adapt to their unique design systems and brand identities.</p>
    
    <p>That's why we built icon.design. Every icon in our library comes with multiple design variations, giving you the freedom to choose the perfect option for your project. We're not just creating icons—we're creating tools that respect the nuance of modern design.</p>

    <h2>What Makes icon.design Different</h2>

    <h3>Multiple Variations Per Icon</h3>
    <p>Unlike traditional icon libraries that offer one design per icon, icon.design provides multiple options for each icon. Need a different approach? We've got you covered. This means less hunting through other libraries and more time focused on what matters: building great products.</p>

    <h3>Pixel-Perfect Precision</h3>
    <p>Every icon is carefully, meticulously designed as a labor of love. We obsess over alignment, stroke consistency, and visual harmony. Each pixel matters, and our icons reflect that commitment to craftsmanship. You get icons that look intentional across every screen size and context.</p>

    <h3>Adjustable Stroke Weight</h3>
    <p>Our line icons are built in SVG with fully customizable stroke weight. Rather than forcing you to choose between thin, regular, or bold versions, you control the stroke weight that fits your design system perfectly. One icon, infinite flexibility—that's the icon.design approach.</p>

    <h3>Clean, Minimalist Design</h3>
    <p>Simplicity is our design philosophy. Our minimalist iconography integrates seamlessly into any user interface, whether you're building a corporate dashboard, creative platform, or consumer app. Clean lines. No unnecessary detail. Just pure, functional design that lets your product shine.</p>

    <h3>Free for Commercial Use</h3>
    <p>Great design shouldn't be locked behind paywalls. Every icon in icon.design is completely free for personal and commercial use. Build your startup, launch your SaaS, deploy your enterprise app—no licensing fees, no restrictions, no surprises.</p>

